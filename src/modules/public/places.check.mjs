import assert from 'node:assert/strict';
import { createPlaceSearch, parsePlaces } from './places.ts';
const feature = { geometry: { type: 'Point', coordinates: [106.1375586, -6.4453801] }, properties: { name: 'Banten', countrycode: 'ID', extent: [104.6513179, -5.4996381, 106.7800127, -7.4565894] } };
const payload = { features: [feature] };
assert.deepEqual(parsePlaces(payload)[0].bbox, [104.6513179, -7.4565894, 106.7800127, -5.4996381]);
assert.equal(parsePlaces(payload)[0].label, 'Banten, Indonesia');
assert.equal(parsePlaces({ features: [{ ...feature, properties: { ...feature.properties, countrycode: 'MY' } }] }).length, 0);
assert.equal(parsePlaces({ features: [{ ...feature, geometry: { type: 'Point', coordinates: [Infinity, 0] } }] }).length, 0);
assert.equal(parsePlaces({ features: Array(9).fill(feature) }).length, 5);
let clock = 1000, calls = 0;
const search = createPlaceSearch(async url => {
  calls++;
  assert.equal(url.searchParams.get('countrycode'), 'ID');
  assert.equal(url.searchParams.get('bbox'), '94,-12,142,7');
  assert.equal(url.searchParams.get('limit'), '5');
  return { ok: true, text: async () => JSON.stringify(payload) };
}, () => clock);
await assert.rejects(search({ q: 'ab' }));
await assert.rejects(search({ q: '<script>' }));
assert.equal((await search({ q: 'Banten' }))[0].name, 'Banten');
await search({ q: 'banten' });
assert.equal(calls, 1);
await assert.rejects(search({ q: 'Jakarta' }), /busy/);
clock += 1000;
await search({ q: 'Jakarta' });
assert.equal(calls, 2);
clock += 300001;
await search({ q: 'Banten' });
assert.equal(calls, 3);
const failed = createPlaceSearch(async () => ({ ok: false }));
await assert.rejects(failed({ q: 'Banten' }), /unavailable/);
